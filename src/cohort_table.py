"""Table 1: cohort characteristics by 14-day readmission (full analysed cohort, n with CMAJ01 recorded).
Labels from the nuMoM2b codebook. Writes results/revision/cohort_table.json and
results/manuscript/tables/table1_cohort.tex. Descriptive only; not used for modelling.
Small-cell suppression: counts 1-10 are shown as <11 (with their rate), plus a complementary cell where needed,
so no suppressed value can be recovered from the column total. Only suppressed values are written to disk."""
MIN_CELL = 11
import json, os
import numpy as np, pandas as pd
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
d = pd.read_csv(os.path.join(ROOT, 'data', 'numom2b_analysis_subset.csv'), low_memory=False)
d = d[d.CMAJ01.notna()].copy()
for c in ('SmokeCat2', 'SmokeCat3', 'V1AG04', 'V1AG05'):
    d[c] = pd.to_numeric(d[c], errors='coerce')
d.loc[d.SmokeCat3.isna() & (d.SmokeCat2 == 2), 'SmokeCat3'] = 0  # same skip-pattern recode as the pipeline
d.loc[d.SmokeCat3 == 3, 'SmokeCat3'] = 2  # merge >40/day into >=20/day (small cell)
y = d.CMAJ01 == 1
YN = {1: 'Yes', 2: 'No'}
CAT = [  # (variable, heading, labels, show only these levels)
    ('AgeCat_V1', 'Age at enrolment, years', {1: '13--17', 2: '18--34', 3: '35--39', 4: '$\\geq$40'}, None),
    ('CRace', 'Race and ethnicity', {1: 'Non-Hispanic White', 2: 'Non-Hispanic Black', 3: 'Hispanic', 4: 'Asian', 5: 'Other'}, None),
    ('Education', 'Education', {1: 'Less than high school', 2: 'High school or GED', 3: 'Some college', 4: 'Associate or technical degree',
                                 5: 'Completed college', 6: 'Beyond college'}, None),
    ('poverty', 'Household income', {1: '$>$200\\% of federal poverty level', 2: '100--200\\%', 3: '$<$100\\%'}, None),
    ('Ins_Govt', 'Government insurance', YN, [1]), ('Ins_Comm', 'Commercial insurance', YN, [1]),
    ('Ins_Pers', 'Paid by personal income', YN, [1]),
    ('BMI_Cat', 'BMI at enrolment, kg/m$^2$', {1: '$<$18.5', 2: '18.5--24.9', 3: '25--29.9', 4: '30--34.9', 5: '$\\geq$35'}, None),
    ('GravCat', 'Gravidity', {1: '1', 2: '2', 3: '$\\geq$3'}, None),
    ('SmokeCat3', 'Smoking in the 3 months before pregnancy', {0: 'None', 1: '$<$20 cigarettes/day', 2: '$\\geq$20 cigarettes/day'}, None),
    ('CMAC15', 'Cesarean delivery', YN, [1]), ('A09A03a', 'Preterm birth ($<$37 weeks)', YN, [1]),
    ('A09A03b', 'Hypertensive disorder (timing not recorded)', YN, [1]),
]
rows, out = [], {'n': int(len(d)), 'events': int(y.sum()), 'variables': {}}
tex = ['% src: results/revision/cohort_table.json (generated by src/cohort_table.py; do not edit by hand)',
       '\\begin{tabular}{lrrr}', '\\toprule',
       f'& \\textbf{{Readmitted}} & \\textbf{{Not readmitted}} & \\textbf{{Readmission}} \\\\',
       f'& \\textbf{{(n = {int(y.sum()):,})}} & \\textbf{{(n = {int((~y).sum()):,})}} & \\textbf{{rate}} \\\\', '\\midrule']
for v, head, lab, only in CAT:
    x = pd.to_numeric(d[v], errors='coerce')
    tex.append(f'\\multicolumn{{4}}{{l}}{{\\textit{{{head}}}}} \\\\')
    # every level takes part in suppression, including undisplayed ones (e.g. "No") and missing, split by outcome
    allc = []
    for code, name in lab.items():
        m = x == code
        if m.sum(): allc.append([name, int((m & y).sum()), int((m & ~y).sum()), not (only and code not in only)])
    mm = ~x.isin(list(lab))
    allc.append(['missing', int((mm & y).sum()), int((mm & ~y).sum()), False])
    sup = [[0 < c[j] < MIN_CELL for j in (1, 2)] for c in allc]
    for j in (0, 1):  # complementary: a column total minus visible cells must never isolate one suppressed cell
        while sum(r[j] for r in sup) == 1 and len(allc) > 1:
            k = min((i for i in range(len(allc)) if not sup[i][j] and allc[i][j + 1] > 0), key=lambda i: allc[i][j + 1], default=None)
            if k is None: break
            sup[k][j] = True
    res = {}
    for (name, a, b, show), (sa, sb) in zip(allc, sup):
        hide = sa or sb
        cell = lambda v, s_: f'<{MIN_CELL}' if s_ else v
        if name == 'missing':
            res['missing'] = {'readmitted': cell(a, sa), 'not_readmitted': cell(b, sb)}
            continue
        if not show: continue
        res[name] = {'readmitted': None if sa else a, 'not_readmitted': None if sb else b,
                     'rate': None if hide else a / (a + b), 'suppressed': hide}
        ca = f'$<${MIN_CELL}' if sa else f'{a} ({a / y.sum() * 100:.1f}\\%)'
        cb = f'$<${MIN_CELL}' if sb else f'{b:,} ({b / (~y).sum() * 100:.1f}\\%)'
        cr = '--' if hide else f'{a / (a + b) * 100:.1f}\\%'
        tex.append(f'\\quad {name} & {ca} & {cb} & {cr} \\\\')
    out['variables'][v] = res
tex += ['\\bottomrule', '\\end{tabular}']
import subprocess as _sp
_git = _sp.run(['git', 'rev-parse', '--short', 'HEAD'], capture_output=True, text=True).stdout.strip() + \
    ('+uncommitted' if _sp.run(['git', 'status', '--porcelain', __file__], capture_output=True, text=True).stdout.strip() else '')
out['_provenance'] = {'script': 'src/cohort_table.py', 'git_hash': _git, 'unit_of_analysis': 'participant',
                     'splitter': 'none (whole analytic cohort, descriptive)', 'groups_passed': False, 'small_cell_min': MIN_CELL}
json.dump(out, open(os.path.join(ROOT, 'results', 'revision', 'cohort_table.json'), 'w'), indent=1)
open(os.path.join(ROOT, 'results', 'manuscript', 'tables', 'table1_cohort.tex'), 'w').write('\n'.join(tex) + '\n')
print('\n'.join(tex[:12])); print('...', len(tex), 'lines'); print({k: v['missing'] for k, v in out['variables'].items()})

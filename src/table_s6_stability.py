"""Supplementary table: up-to-discharge variables selected by L1 logistic regression in >= half of 100 half-sample
refits (stability selection). EXPLORATORY, POST HOC. Loads results/expanded/expanded.json only; short descriptions
paraphrase the nuMoM2b codebook labels stored in that file."""
import json, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
E = json.load(open(os.path.join(ROOT, 'results', 'expanded', 'expanded.json')))['tiers']['tier2_to_discharge']['L1_LR']
SHORT = {'V3EA02b': 'Visit 3 (22--29 wk): bothered by tiredness or low energy', 'CMAA01m': 'Admitted to labour and delivery for a maternal medical or obstetric condition',
         'V1AD12c': 'Previous cervical surgery: cryotherapy', 'CMAC15': 'Cesarean delivery',
         'V1AD02a': 'Preconception counselling: folic acid', 'U2CD05': 'Right uterine artery Doppler, systolic/diastolic ratio',
         'V1AD12b': 'Previous cervical surgery: LEEP', 'V1AD12a': 'Previous cervical surgery: cone biopsy',
         'V1AG02c': 'Episodes of four or more drinks, three months before pregnancy', 'V1BA04b': 'Waist circumference (visit 1)',
         'CMAG06i': 'Other prescribed medication during the delivery stay', 'CMAG02i1': 'Other prophylactic antibiotic during the delivery stay'}
rows = [r for r in E['stability_top30'] if r['freq'] >= 0.5]
assert all(r['var'] in SHORT for r in rows), [r['var'] for r in rows if r['var'] not in SHORT]
tex = ['\\begin{tabular}{lp{9.5cm}r}', '\\toprule', '\\textbf{Variable} & \\textbf{Description} & \\textbf{Frequency} \\\\', '\\midrule']
tex += [f"\\texttt{{{r['var']}}} & {SHORT[r['var']]} & {r['freq']:.2f} \\\\" for r in rows]
tex += ['\\bottomrule', '\\end{tabular}']
out = os.path.join(ROOT, 'results', 'manuscript', 'tables', 'tableS6_stability_selection.tex')
open(out, 'w').write('% generated by src/table_s6_stability.py from results/expanded/expanded.json\n' + '\n'.join(tex) + '\n')
print('wrote', out, len(rows), 'rows')
